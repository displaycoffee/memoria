/* Scripts */
import type { ThemeMode } from '@displaycoffee/tokens';
import { colors } from '@/_core/data/colors';
import themeJson from '@/_core/tokens/theme.json' with { type: 'json' }; // generated by tokens-generate (@displaycoffee/tokens)

/* giscus themes built from the color tokens
   Note: used at build time by Comments.tsx, which puts each theme on the comments container for comments.ts to send to giscus
   Note: giscus loads a custom theme as a stylesheet in its iframe, so it gets a data: URL (a hosted file would need CORS, and localhost is blocked from giscus.app in dev)
   Note: fonts come from Google Fonts, which allows cross-origin loading (our self-hosted fonts would need CORS headers) */
export const commentsTheme = {
	fonts: () => {
		// Google Fonts URL for the body and header fonts, in the regular / bold / italic styles we use
		const { font } = themeJson;
		const families = [font['name-header'], font['name-body']].map(
			(name) => `family=${name.replace(/ /g, '+')}:ital,wght@0,400;0,700;1,400;1,700`,
		);
		return `https://fonts.googleapis.com/css2?${families.join('&')}&display=swap`;
	},
	css: (theme: ThemeMode) => {
		// Get a color token for this theme, using the -dark variant when there is one
		const tokens = colors as Record<string, string | false>;
		const color = (name: string) => String((theme === 'dark' && tokens[`${name}-dark`]) || tokens[name]);
		const mix = (name: string, percent: number, base = 'bg') => `color-mix(in srgb, ${color(name)} ${percent}%, ${color(base)})`;

		// Start from giscus's built-in theme of the same mode, then swap GitHub's colors for ours
		const variables = {
			'--color-fg-default': color('body'),
			'--color-fg-muted': mix('body', 75),
			'--color-fg-subtle': mix('body', 60),
			'--color-canvas-default': color('bg'),
			'--color-canvas-overlay': color('bg'),
			'--color-canvas-inset': mix('body', 4),
			'--color-canvas-subtle': mix('body', 6),
			'--color-border-default': mix('border', 35),
			'--color-border-muted': mix('border', 20),
			'--color-neutral-muted': mix('body', 20),
			'--color-accent-fg': color('link'),
			'--color-accent-emphasis': color('link'),
			'--color-accent-muted': mix('link', 40),
			'--color-accent-subtle': mix('link', 10),
			'--color-danger-fg': color('required'),
			'--color-btn-text': color('body'),
			'--color-btn-bg': color('bg'),
			'--color-btn-border': color('border'),
			'--color-btn-hover-bg': mix('body', 8),
			'--color-btn-hover-border': color('border'),
			'--color-btn-active-bg': mix('body', 12),
			'--color-btn-active-border': color('border'),
			'--color-btn-selected-bg': mix('body', 8),
			'--color-btn-primary-text': color('button-primary-body'),
			'--color-btn-primary-bg': color('button-primary-bg'),
			'--color-btn-primary-border': color('button-primary-border'),
			'--color-btn-primary-hover-bg': mix('button-primary-bg', 85),
			'--color-btn-primary-hover-border': color('button-primary-border'),
			'--color-btn-primary-selected-bg': color('button-primary-bg'),
			'--color-btn-primary-disabled-text': mix('button-primary-body', 60, 'button-primary-bg'),
			'--color-btn-primary-disabled-bg': mix('button-primary-bg', 50),
			'--color-btn-primary-disabled-border': mix('button-primary-border', 50),
			'--color-segmented-control-bg': mix('body', 8),
			'--color-segmented-control-button-bg': color('bg'),
			'--color-segmented-control-button-selected-border': color('border'),
			'--color-social-reaction-bg-hover': mix('body', 8),
			'--color-social-reaction-bg-reacted-hover': mix('link', 20),
		};
		const properties = Object.entries(variables)
			.map(([property, value]) => `${property}:${value}`)
			.join(';');

		// Headings match memoria's (_typography.scss), with sizes in rem from a 16px base
		const { font } = themeJson;
		const headers = 'h1,h2,h3,h4,h5,h6';
		const header = [
			`font-family:${font['family-header']}`,
			`font-weight:${font['weight-header']}`,
			font['style-header'] ? `font-style:${font['style-header']}` : '',
			font['transform-header'] ? `text-transform:${font['transform-header']}` : '',
			`color:${color('header')}`,
		].filter(Boolean);
		const headerSizes = { h1: 34, h2: 30, h3: 26, h4: 22, 'h5,h6': 20 };

		return [
			`@import url('${commentsTheme.fonts()}');`,
			`@import url('https://giscus.app/themes/${theme}.css');`,
			`main{${properties}}`,
			`body{font-family:${font['family-body']}}`,
			`${headers}{${header.join(';')}}`,
			...Object.entries(headerSizes).map(([selector, size]) => `${selector}{font-size:${size / 16}rem}`),
			`:is(${headers}) a{color:inherit}`,
			`:is(${headers}) a:is(:active,:hover){color:${color('link')}}`,
			`* { border-radius: 0 !important; }`,
			`.color-box-border-info { border-color: var(--color-border-muted); }`,
			`#__next .gsc-comments-count .underline { text-decoration: none; }`,
		].join('');
	},
	url: (theme: ThemeMode) => {
		// Theme as a data: URL for giscus's data-theme / setConfig
		return `data:text/css,${encodeURIComponent(commentsTheme.css(theme))}`;
	},
};
